#---------------------------------------------------------------------
# Numeric Type
#---------------------------------------------------------------------
print("---------------------1) Numeric Data Type ---------------------")
X = 11
Y = 89.90
Z = 8+6j

print(X)
print(type(X))

print(Y)
print(type(Y))

print(Z)
print(type(Z))

#---------------------------------------------------------------------
# Text Type
#---------------------------------------------------------------------
print("----------------------2) Text Data Type --------------------------")

Name = "Samarth"

print(Name)
print(type(Name))

#---------------------------------------------------------------------
# Sequence Type
#---------------------------------------------------------------------
print("----------------------3) Sequence Data Type ----------------------")

Data1 = [11,21,51,101]
Data2 = (11,21,51,101)
Data3 = range(1,8,2)
#       range(start,End,Step)  

print(Data1)
print(type(Data1))

print(Data2)
print(type(Data2))

print(Data3)
print(type(Data3))
print(list(Data3))

#-------------------------------------------------------------------------
# Set Type
#-------------------------------------------------------------------------
print("------------------------4) Set Data Type -------------------------")

Marks = {78,92,75,65}

print(Marks)
print(type(Marks))

#------------------------------------------------------------------------
# Mapping Type
#------------------------------------------------------------------------
print("------------------------5) Mapping Data Type ---------------------")

Students = {"Name" : "Samarth","Age" : 23,"Marks" : 85}

print(Students)
print(type(Students))

#------------------------------------------------------------------------
# Binary Type
#------------------------------------------------------------------------
print("------------------------6) Binary Data Type-----------------------")

B1 = b"Hello"
B2 = bytearray(b"Hello")

print(B1)
print(type(B1))

print(B2)
print(type(B2))

#------------------------------------------------------------------------
# None Type
#------------------------------------------------------------------------
print("------------------------7) None Data Type-----------------------")

Result = None

print(Result)
print(type(Result))

#------------------------------------------------------------------------
# None Type
#------------------------------------------------------------------------
print("------------------------8) Boolean Data Type-----------------------")

Flag1 = True
Flag2 = False

print(Flag1)
print(type(Flag1))

print(Flag2)
print(type(Flag2))








